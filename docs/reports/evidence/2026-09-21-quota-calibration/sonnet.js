'use strict';

// The one session that ran a whole fankeel route with Sonnet 5 as the main
// controller: what it cost, what model every turn in it actually used, and what
// its per-stage split looks like under each of the two boundary records.
//
//   node docs/reports/evidence/2026-09-21-quota-calibration/sonnet.js
//
// This is one arm with no pair, and the output says so rather than leaving a
// reader to infer it. It cannot give the token multiple that
// docs/reports/2026-09-21-long-task-projection.md's projection turns on — that
// needs the same task run on Opus — but it does answer the half a single arm can:
// whether a Sonnet main controller holds the pipeline at all, and what the run
// cost end to end.
//
// `spend` is computed here rather than read, because the registry does not have
// it. `hooks/leave.js` writes `spend` at SessionEnd, and at the time this was
// written that terminal was still open — so the record carries `clock`, `moves`
// and `burn` but no `spend`, and a live session's quota reading and its own
// registry record can never meet. The three library calls below are the same
// three `hooks/leave.js` makes, in the same order, so the figure sits on exactly
// the basis every other `spend` in the registry does.

const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { execSync } = require('node:child_process');
const registry = require('../../../../lib/registry.js');
const usage = require('../../../../lib/usage.js');
const prices = require('../../../../lib/prices.js');
const live = require('../../../../lib/live.js');

const ROOT = path.resolve(__dirname, '..', '..', '..', '..');
const PROJECTS = path.join(live.liveConfigDir() || path.join(os.homedir(), '.claude'), 'projects');
const HERE = path.join(PROJECTS, ROOT.replace(/[^A-Za-z0-9]/g, '-'));

const SESSION = 'c5571add-ec3d-4987-826e-40365c2775e2';
const TRANSCRIPT = path.join(HERE, SESSION + '.jsonl');

const out = [];
const say = (line) => out.push(line === undefined ? '' : String(line));
const usd = (n) => '$' + n.toFixed(4);
const num = (n) => Math.round(n).toLocaleString('en-US');

const data = registry.readSession(ROOT, SESSION);
if (!data) throw new Error('no registry entry for ' + SESSION);
if (!fs.existsSync(TRANSCRIPT)) throw new Error('no transcript at ' + TRANSCRIPT);

say('# the Sonnet-5-as-main-controller run');
say('#');
say('# generated by docs/reports/evidence/2026-09-21-quota-calibration/sonnet.js');
say('# registry entry ' + path.join(ROOT, '.fankeel', 'sessions', SESSION + '.json'));
say('# prices.verified ' + prices.verified);
say('');
say('task     ' + data.task);
say('class    ' + data.class + '   route ' + (data.route || []).join(' -> '));
say('version  ' + data.version + '   (the plugin version this ran under)');
say('started  ' + data.started);
say('land     ' + JSON.stringify(data.land));
say('spend in the registry  ' + (data.spend ? 'present' : 'ABSENT — hooks/leave.js had not run'));
say('');

// Which model actually ran. The whole point of the arm: a main controller set to
// Sonnet is a claim about every turn, not about a setting.
say('## block 1 — what model every turn used');
function modelsIn(file) {
    const seen = new Map();
    const counts = {};
    for (const line of fs.readFileSync(file, 'utf8').split('\n')) {
        if (!line.trim()) continue;
        let j;
        try { j = JSON.parse(line); } catch (e) { continue; }
        if (j.type !== 'assistant' || !j.message || !j.message.usage) continue;
        const id = typeof j.message.model === 'string' ? j.message.model : '(none)';
        const key = j.requestId || j.uuid;
        if (seen.has(key)) continue;
        seen.set(key, id);
        counts[id] = (counts[id] || 0) + 1;
    }
    return counts;
}
const mainCounts = modelsIn(TRANSCRIPT);
say('main transcript, one entry per API response:');
for (const [id, n] of Object.entries(mainCounts)) say('  ' + id + '   ' + n);

const subDir = path.join(HERE, SESSION, 'subagents');
const agentCounts = {};
let agentFiles = 0;
if (fs.existsSync(subDir)) {
    for (const f of fs.readdirSync(subDir).sort()) {
        if (!f.endsWith('.jsonl')) continue;
        agentFiles += 1;
        for (const [id, n] of Object.entries(modelsIn(path.join(subDir, f)))) {
            agentCounts[id] = (agentCounts[id] || 0) + n;
        }
    }
}
say('subagents (' + agentFiles + ' transcripts):');
if (!agentFiles) say('  (none)');
for (const [id, n] of Object.entries(agentCounts)) say('  ' + id + '   ' + n);

// `hooks/leave.js`'s own three calls: windowsFrom over the clock, summariseTree
// over the transcript with those windows, then the per-stage models it keeps.
const windows = registry.windowsFrom(data.clock);
const seen = usage.summariseTree(TRANSCRIPT, windows.length ? { stages: windows } : undefined);

const keyed = (b) => (b && typeof b === 'object' ? b : null);
const spend = {};
for (const [stage, bucket] of Object.entries(keyed(seen.usage.stages) || {})) {
    spend[stage] = { requests: bucket.requests, models: bucket.models };
}
for (const [stage, bucket] of Object.entries(keyed(seen.usage.subagents && seen.usage.subagents.stages) || {})) {
    const at = spend[stage] || (spend[stage] = { requests: 0, models: {} });
    at.subagents = { requests: bucket.requests, models: bucket.models };
}

const price = (models) => {
    const c = prices.costOf(models);
    if (c.unpriced.length) throw new Error('unpriced model: ' + c.unpriced.join(','));
    return c.usd;
};
const tokensOf = (models) => {
    let n = 0;
    for (const m of Object.values(models || {})) n += m.input + m.output + m.cacheRead + m.cacheWrite5m + m.cacheWrite1h;
    return n;
};

say('');
say('## block 2 — the spend hooks/leave.js would have written');
say('model as summariseTree reads it: ' + seen.model);
say('requests: ' + seen.usage.requests + ' own, '
    + (seen.usage.subagents ? seen.usage.subagents.requests : 0) + ' agents');
say('');
say(['stage', 'reqs', 'ownUsd', 'agentReqs', 'agentUsd', 'stageUsd', 'tokens'].join('\t'));
let totalUsd = 0;
let totalTokens = 0;
for (const [stage, b] of Object.entries(spend)) {
    const o = price(b.models);
    const a = b.subagents ? price(b.subagents.models) : 0;
    const t = tokensOf(b.models) + (b.subagents ? tokensOf(b.subagents.models) : 0);
    totalUsd += o + a;
    totalTokens += t;
    say([stage, b.requests, usd(o), b.subagents ? b.subagents.requests : 0, usd(a), usd(o + a), num(t)].join('\t'));
}
say(['TOTAL', '', '', '', '', usd(totalUsd), num(totalTokens)].join('\t'));

// The crosscheck the per-stage sum has to pass: the same two model maps read
// without any window bucketing at all. A stage window that swallowed or dropped a
// request would show up here and nowhere else.
const wholeOwn = price(seen.usage.models);
const wholeAgents = seen.usage.subagents ? price(seen.usage.subagents.models) : 0;
say('');
say('crosscheck against the un-bucketed whole-session totals');
say('  own    ' + usd(wholeOwn));
say('  agents ' + usd(wholeAgents));
say('  sum    ' + usd(wholeOwn + wholeAgents)
    + '   difference from the stage sum: ' + usd(wholeOwn + wholeAgents - totalUsd));

say('');
say('## block 3 — the same split under each boundary record');
say('The left column is what the registry holds. The right is what the boundaries');
say('become once each one sits at the `task.js stage` command that caused it.');
say('This run is 53 minutes, so a boundary a few minutes late is a large fraction');
say('of a stage — which is why this arm is where the defect showed up at all.');
say('');

function stageCalls(file, notBefore) {
    const found = [];
    for (const line of fs.readFileSync(file, 'utf8').split('\n')) {
        if (!line.trim()) continue;
        let j;
        try { j = JSON.parse(line); } catch (e) { continue; }
        if (j.type !== 'assistant' || !j.message || !j.timestamp) continue;
        const at = Date.parse(j.timestamp);
        if (!Number.isFinite(at) || at < notBefore) continue;
        for (const c of j.message.content || []) {
            if (c.type !== 'tool_use') continue;
            const m = JSON.stringify(c.input || {}).match(/task\.js stage ([a-z]+)/);
            if (m) found.push({ stage: m[1], at });
        }
    }
    return found;
}

const calls = stageCalls(TRANSCRIPT, Date.parse(data.started));
const observed = windows.map((w) => ({ stage: w.stage, from: w.from, to: w.to }));
say(['stage', 'registry clock', 'task.js stage call', 'drift'].join('\t'));
for (let i = 0; i < windows.length; i += 1) {
    const cands = calls.filter((c) => c.stage === windows[i].stage && c.at <= windows[i].from);
    const call = i === 0 || !cands.length ? null : cands[cands.length - 1];
    if (call && call.at > observed[i - 1].from) observed[i].from = call.at;
    say([windows[i].stage,
        Number.isFinite(windows[i].from) ? new Date(windows[i].from).toISOString() : 'session start',
        call ? new Date(call.at).toISOString() : '(none — start put it here)',
        call ? ((windows[i].from - call.at) / 60000).toFixed(1) + ' min late' : '—'].join('\t'));
}
for (let i = 0; i + 1 < observed.length; i += 1) observed[i].to = observed[i + 1].from;

function splitOf(wins) {
    const s = usage.summariseTree(TRANSCRIPT, { stages: wins });
    const rows = {};
    for (const side of [s.usage.stages, s.usage.subagents && s.usage.subagents.stages]) {
        for (const [stage, b] of Object.entries(side || {})) {
            rows[stage] = (rows[stage] || 0) + price(b.models);
        }
    }
    return rows;
}
const a = splitOf(windows);
const b = splitOf(observed);
const totA = Object.values(a).reduce((x, y) => x + y, 0);
const totB = Object.values(b).reduce((x, y) => x + y, 0);
say('');
say(['stage', 'clock usd', 'clock share', 'command usd', 'command share', 'change'].join('\t'));
for (const w of windows) {
    const x = a[w.stage] || 0;
    const y = b[w.stage] || 0;
    say([w.stage, usd(x), (100 * x / totA).toFixed(1) + '%', usd(y), (100 * y / totB).toFixed(1) + '%',
        (y - x >= 0 ? '+' : '') + usd(y - x)].join('\t'));
}
say(['TOTAL', usd(totA), '100.0%', usd(totB), '100.0%',
    'difference ' + usd(totB - totA) + ' — a reattribution, not a recount'].join('\t'));

let sha = 'unknown';
try {
    sha = execSync('git rev-parse --short HEAD', { cwd: ROOT }).toString().trim();
} catch (e) {
    sha = 'unknown';
}
const outPath = path.join(__dirname, 'sonnet-at-' + sha + '.txt');
fs.writeFileSync(outPath, out.join('\n') + '\n');
process.stdout.write(out.join('\n') + '\n');
process.stdout.write('\nwritten to ' + outPath + '\n');
