'use strict';

// Every figure in the report that is not present in a committed output, sorted
// into why. This is the check the report's own disclosure paragraph points at
// rather than restating, because any total written into the page becomes one more
// figure this script counts.
//
//   node docs/reports/evidence/2026-09-21-quota-calibration/roundings.js
//
// Two earlier versions of this check were wrong in ways worth keeping written
// down, because both classes are invisible unless you go looking:
//
// - The first used `String.includes`. A rounding is exactly the case where the
//   short form is a prefix of the long one, so `6.98` was "found" inside
//   `6.9784` and the check was blind to the class it existed to find. Whole-token
//   matching — not bounded by a digit, a comma or a point on either side — is
//   what fixes that.
// - The second reported a breakdown that was arithmetic over a guess: 6 sha
//   fragments + 7 roundings + 2 sums = 15, when the page held 5 shas and one
//   figure fit none of the three buckets. Hence this file: the breakdown is
//   computed, and the categories are named in the page while the counts are left
//   here.
//
// What it still cannot catch, stated because a reader will otherwise assume
// otherwise: a figure copied from the WRONG row of an output is present and
// verbatim, so it passes. §3 once carried 16,536 where the sum of two rows was
// wanted, and §7's table once summed to 12 against its own prose's 13. Both were
// caught by a person reading, not by this.

const fs = require('node:fs');
const path = require('node:path');
const { execSync } = require('node:child_process');

const ROOT = path.resolve(__dirname, '..', '..', '..', '..');
const REPORT = path.join(ROOT, 'docs', 'reports', '2026-09-21-quota-calibration.md');

const out = [];
const say = (l) => out.push(l === undefined ? '' : String(l));

// Everything a reader could check the page against: this directory's outputs and
// captures, plus the sibling report's capture, which reading A comes from.
let hay = '';
const sources = [];
for (const f of fs.readdirSync(__dirname).sort()) {
    if (!f.endsWith('.txt')) continue;
    // Never its own output. It writes `roundings-at-<sha>.txt` into this
    // directory, and that file lists every figure it found missing — so reading
    // it back would make each of those figures "present" on the next run, and the
    // check would report clean for exactly the numbers it had just flagged.
    if (/^roundings-at-/.test(f)) continue;
    hay += fs.readFileSync(path.join(__dirname, f), 'utf8') + '\n';
    sources.push(f);
}
const sibling = path.join(ROOT, 'docs', 'reports', 'evidence', '2026-09-21-long-task-projection',
    'quota-capture-260920T163041Z.txt');
if (fs.existsSync(sibling)) {
    hay += fs.readFileSync(sibling, 'utf8');
    sources.push('../2026-09-21-long-task-projection/quota-capture-260920T163041Z.txt');
}

const esc = (n) => n.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const wholeToken = (n) => new RegExp('(?<![0-9.,])' + esc(n) + '(?![0-9.,])').test(hay);

const report = fs.readFileSync(REPORT, 'utf8');
const shas = new Set(report.match(/\b[0-9a-f]{7}\b/g) || []);
const figures = [...new Set(report.match(/[0-9][0-9,]*(?:\.[0-9]+)?/g) || [])].filter((n) => n.length > 1);

const absent = figures.filter((n) => !wholeToken(n) && !wholeToken(n.replace(/,/g, '')));
const shaFrag = absent.filter((n) => [...shas].some((s) => s.includes(n)));
const rest = absent.filter((n) => !shaFrag.includes(n));

say('# figures in docs/reports/2026-09-21-quota-calibration.md not present in any output');
say('#');
say('# generated by docs/reports/evidence/2026-09-21-quota-calibration/roundings.js');
say('# checked against: ' + sources.join(', '));
say('');
say('figures in the report           ' + figures.length);
say('absent as a whole token         ' + absent.length);
say('  sha fragments                 ' + shaFrag.length + '   ' + shaFrag.sort().join(' '));
say('  everything else               ' + rest.length);
say('');
say('everything else, and what each one is:');
for (const n of rest.sort()) {
    const near = [...new Set(hay.match(new RegExp(esc(n) + '[0-9]*', 'g')) || [])]
        .sort((a, b) => b.length - a.length)[0];
    say('  ' + n.padEnd(12) + (near && near !== n
        ? 'a rounding of ' + near
        : 'not a prefix of anything in the outputs — a stated sum, a filename date, or a figure the page flags itself'));
}

let sha = 'unknown';
try { sha = execSync('git rev-parse --short HEAD', { cwd: ROOT }).toString().trim(); } catch (e) { sha = 'unknown'; }
const outPath = path.join(__dirname, 'roundings-at-' + sha + '.txt');
fs.writeFileSync(outPath, out.join('\n') + '\n');
process.stdout.write(out.join('\n') + '\n');
process.stdout.write('\nwritten to ' + outPath + '\n');
