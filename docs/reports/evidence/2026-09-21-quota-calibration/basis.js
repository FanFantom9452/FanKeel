'use strict';

// Whether the basis every dollar figure in docs/reports stands on — transcript
// usage priced by `lib/prices.js` — agrees with Claude Code's own
// `cost.total_cost_usd`, checked at the two instants where both numbers exist.
//
//   node docs/reports/evidence/2026-09-21-quota-calibration/basis.js
//
// This is the control on the whole measurement. Every cost figure this
// repository has ever published is transcript-derived; the two statusline
// captures are the only places a second, independent figure for the same session
// at the same moment is on record. If the two agree, the basis is sound. Where
// they do not, the direction of the gap decides whether a rate computed from the
// transcript is an estimate or a bound — and it turns out to be a bound.
//
// It also computes each meter's rate from the one segment that moved both, which
// is the reading that needs no assumption about what a window holds when it
// opens: the same spend drove the five-hour meter from 2 to 13 and the seven-day
// meter from 0 to 3, so the segment gives each a rate with no window history in
// the arithmetic.
//
// One thing this file decides on its own: only the two sessions that had a
// request inside the five-hour window are summed for the A..B segment. That is
// not a sample — block 2 of windows.js establishes over all transcripts on the
// machine that there were exactly two, so summing them is summing the window.

const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { execSync } = require('node:child_process');
const usage = require('../../../../lib/usage.js');
const prices = require('../../../../lib/prices.js');
const live = require('../../../../lib/live.js');

const ROOT = path.resolve(__dirname, '..', '..', '..', '..');
const PROJECTS = path.join(live.liveConfigDir() || path.join(os.homedir(), '.claude'), 'projects');

// This repository's own transcripts. The directory name is what Claude Code
// makes of an absolute path: EACH non-alphanumeric character becomes a dash, not
// each run — `F:\ymlab\fankeel` is `F--ymlab-fankeel`, with two dashes for the
// colon and the separator. Collapsing runs gave one dash and found nothing.
const HERE = path.join(PROJECTS, ROOT.replace(/[^A-Za-z0-9]/g, '-'));

// The session that was open across both captures, and the Sonnet-main test that
// ran inside the second segment. Named because the captures are of these two and
// nothing else; block 2 of windows.js is what establishes there were no others.
const OPUS = '417fef89-fd54-4f75-b5df-87b5d636724d';
const SONNET = 'c5571add-ec3d-4987-826e-40365c2775e2';

// Reading A: the figures are the committed capture's own, at
// docs/reports/evidence/2026-09-21-long-task-projection/quota-capture-260920T163041Z.txt
const A = { at: Date.parse('2026-09-20T16:30:41.226Z'), claudeCode: 12.561022100000004, five: 2, seven: 0 };
// Reading B: the figures are quota-capture-260920T203515Z.txt beside this file.
const B = { at: Date.parse('2026-09-20T20:35:15.617Z'), claudeCode: 109.1054969, five: 13, seven: 3 };

// The one compaction inside the A..B segment, from the transcript's own
// `compact_boundary` line. Located rather than assumed — see block 3.
const COMPACT_AT = Date.parse('2026-09-20T20:33:29.833Z');

const WINDOWS = [
    { stage: 'upToA', from: -Infinity, to: A.at },
    { stage: 'AtoB', from: A.at, to: B.at },
    { stage: 'afterB', from: B.at, to: Infinity },
];

const out = [];
const say = (line) => out.push(line === undefined ? '' : String(line));
const usd = (n) => '$' + n.toFixed(4);
const num = (n) => Math.round(n).toLocaleString('en-US');

function costOf(sessionId, stage) {
    const seen = usage.summariseTree(path.join(HERE, sessionId + '.jsonl'), { stages: WINDOWS });
    if (!seen) return { usd: 0, tokens: 0, requests: 0 };
    let dollars = 0;
    let tokens = 0;
    let requests = 0;
    for (const side of [seen.usage.stages, seen.usage.subagents && seen.usage.subagents.stages]) {
        const b = (side || {})[stage];
        if (!b) continue;
        requests += b.requests;
        const real = {};
        for (const [id, m] of Object.entries(b.models)) if (id !== '<synthetic>') real[id] = m;
        const c = prices.costOf(real);
        if (c.unpriced.length) throw new Error('unpriced model: ' + c.unpriced.join(','));
        dollars += c.usd;
        for (const m of Object.values(real)) tokens += m.input + m.output + m.cacheRead + m.cacheWrite5m + m.cacheWrite1h;
    }
    return { usd: dollars, tokens, requests };
}

say('# the transcript basis against Claude Code\'s own, at both captures');
say('#');
say('# generated by docs/reports/evidence/2026-09-21-quota-calibration/basis.js');
say('# transcripts read from ' + HERE);
say('# prices.verified ' + prices.verified);
say('');

say('## block 1 — the control');
const opusToA = costOf(OPUS, 'upToA');
const opusAB = costOf(OPUS, 'AtoB');
const tA = opusToA.usd;
const tB = tA + opusAB.usd;
say('session ' + OPUS.slice(0, 8) + ', cumulative cost at each capture');
say(['at', 'transcript basis', "Claude Code's own", 'gap', 'gap %'].join('\t'));
const row = (label, transcript, claudeCode) => {
    const gap = transcript - claudeCode;
    say([label, usd(transcript), usd(claudeCode),
        (gap >= 0 ? '+' : '') + usd(gap),
        (gap >= 0 ? '+' : '') + (100 * gap / claudeCode).toFixed(2) + '%'].join('\t'));
    return gap;
};
const gA = row('reading A 16:30:41Z', tA, A.claudeCode);
const gB = row('reading B 20:35:15Z', tB, B.claudeCode);
say('');
say('the gap that opened between the two captures: ' + usd(gB - gA));

say('');
say('## block 2 — where that gap could come from');
say('One compaction sits inside the A..B segment. A compaction re-reads the whole');
say('context to summarise it, and that call is not written to the transcript as an');
say('assistant turn, so its tokens are outside this basis by construction.');
say('');
// Located from the transcript rather than asserted: the boundary line and the
// summary line Claude Code writes for a compaction, and the largest raw
// `input_tokens` on any request — which is what a full uncached read would show
// up as if one were recorded.
const lines = fs.readFileSync(path.join(HERE, OPUS + '.jsonl'), 'utf8').split('\n');
const marks = [];
const byRequest = new Map();
for (const l of lines) {
    if (!l.trim()) continue;
    let j;
    try { j = JSON.parse(l); } catch (e) { continue; }
    const s = JSON.stringify(j);
    if (/"isCompactSummary":true/.test(s) || /"subtype":"compact_boundary"/.test(s)) {
        marks.push({ at: j.timestamp, type: j.type, compact: /isCompactSummary/.test(s) });
    }
    if (j.type === 'assistant' && j.message && j.message.usage && j.requestId) {
        byRequest.set(j.requestId, { at: j.timestamp, u: j.message.usage, model: j.message.model });
    }
}
say('compaction markers in this transcript: ' + marks.length);
for (const m of marks) {
    say('  ' + m.at + '  ' + m.type + (m.compact ? '  isCompactSummary' : '  compact_boundary')
        + (Date.parse(m.at) > A.at && Date.parse(m.at) < B.at ? '   <- inside A..B' : ''));
}
const biggest = [...byRequest.values()].sort((a, b) => (b.u.input_tokens || 0) - (a.u.input_tokens || 0))[0];
say('largest raw input_tokens on any one request: ' + (biggest ? biggest.u.input_tokens : 'n/a')
    + ' — every request is a cache read, so no full-context read is recorded here');
say('minutes from the compaction to reading B: ' + ((B.at - COMPACT_AT) / 60000).toFixed(1));
say('');
say('So the A..B spend below is a FLOOR, and every per-point rate derived from it');
say('is a lower bound rather than a point estimate.');

say('');
say('## block 3 — the segment that moved both meters');
const sonnetAB = costOf(SONNET, 'AtoB');
const segUsd = opusAB.usd + sonnetAB.usd;
const segTokens = opusAB.tokens + sonnetAB.tokens;
const segReq = opusAB.requests + sonnetAB.requests;
say('length     ' + ((B.at - A.at) / 60000).toFixed(1) + ' minutes');
say('requests   ' + segReq + '   (' + opusAB.requests + ' from ' + OPUS.slice(0, 8)
    + ', ' + sonnetAB.requests + ' from ' + SONNET.slice(0, 8) + ')');
say('tokens     ' + num(segTokens));
say('usd        ' + usd(segUsd) + '   (floor, per block 2)');
say('');

// A displayed integer p means [p-0.5, p+0.5). A displayed 0 does not widen
// downward, because a meter cannot read below zero.
const lowEnd = (p) => (p === 0 ? 0 : p - 0.5);
const meter = (label, from, to) => {
    const dLo = lowEnd(to) - (from + 0.5);
    const dHi = to + 0.5 - lowEnd(from);
    const perLo = segUsd / dHi;
    const perHi = segUsd / dLo;
    say(label + ': ' + from + '% -> ' + to + '%,  delta ' + dLo.toFixed(1) + '-' + dHi.toFixed(1) + ' points');
    say('  $ per point        $' + perLo.toFixed(2) + '-$' + perHi.toFixed(2) + '   (each a floor)');
    say('  a full 100 points  $' + num(perLo * 100) + '-$' + num(perHi * 100));
    return [perLo, perHi];
};
const five = meter('five-hour meter', A.five, B.five);
say('');
const seven = meter('seven-day meter', A.seven, B.seven);
say('');
say('one seven-day point is worth ' + (seven[0] / five[1]).toFixed(1) + '-'
    + (seven[1] / five[0]).toFixed(1) + ' five-hour points of the same spend.');

let sha = 'unknown';
try {
    sha = execSync('git rev-parse --short HEAD', { cwd: ROOT }).toString().trim();
} catch (e) {
    sha = 'unknown';
}
const outPath = path.join(__dirname, 'basis-at-' + sha + '.txt');
fs.writeFileSync(outPath, out.join('\n') + '\n');
process.stdout.write(out.join('\n') + '\n');
process.stdout.write('\nwritten to ' + outPath + '\n');
