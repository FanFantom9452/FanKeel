'use strict';

// Per-session, per-stage spend and token print-out — the first row of the
// "does moving the main controller to Sonnet make a seven-stage long task
// cheaper" projection. It reprints what is already on disk under
// `.fankeel/sessions/` rather than running anything new, so the row after
// this one can project from real numbers without a paid long task first.
//
//   node docs/reports/evidence/2026-09-21-long-task-projection/stages.js
//
// All pricing and stage-bucketing goes through the library the rest of the
// repo already uses: `lib/registry.js`'s `seriesOf` for what a stage's
// window and recorded spend are, `lib/prices.js`'s `costOf` for what a set
// of models cost, and `lib/spend.js`'s `sessionsOf` for the whole-session
// total block 1's per-stage sum is checked against in block 2. The
// request-count bucket printed in block 1 also comes from `lib/spend.js`,
// through its exported `buckets()` rather than the module's own un-exported
// `rangeFor` — called on a one-row array, so whichever of the four ranges
// comes back with `count: 1` is this session's bucket, with no boundary
// copied here and no change made to `lib/`.
//
// Two populations, because block 1/2 and block 3 answer different
// questions:
//
// - Block 1 and block 2 cover every session that carries a `spend` field —
//   79 of them on the day this was written, `<50` and `50-199` request
//   buckets included. Each block 1 row names its session's bucket in the
//   `bucket` column; a reader who only wants the long-task end of that
//   (`200-799`, `800+`) filters on that column themselves rather than this
//   script deciding it for them.
//
// - Block 3's rolling windows answer a different question — what an
//   account-level 5-hour or 7-day usage cap actually saw — and a cap does
//   not care which request-count bucket a session falls in. Filtering short
//   sessions out of block 3 would understate every window's real total, so
//   block 3 deliberately keeps the same full, unfiltered population as
//   block 1 and block 2.
//
// Two further choices this file makes on its own, stated here because
// nothing else states them:
//
// - `who`: a stage's parent tokens and its subagents' tokens print as two
//   rows (`who` = `parent` / `agents`), not added into one. That mirrors
//   `lib/station.js` lines 392-404, which keeps them as two separate
//   `prices.costOf` calls — `w.spend.models` for the parent side,
//   `w.spend.subagents.models` for the agents side — before ever combining
//   them. `usd` follows the same split: a side with no priced model in it
//   prints `—`, not `$0`, for the reason `station.js`'s own comment gives —
//   `costOf` returns `usd: 0` for an unpriced set of models, which is not
//   distinguishable from a side that genuinely spent nothing.
//
// - Every stage's tokens are stamped at its `to` timestamp, not spread
//   across its duration. A stage's tokens were generated by requests
//   somewhere inside the window, but nothing on disk says when inside it —
//   spreading them evenly would be a model this script invented, not a fact
//   it read. `to` is where `lib/registry.js`'s own `clock` entry for the
//   stage ends, so it is also the one timestamp every priced stage already
//   carries, comparable across sessions with no extra assumption.
//
// Block 3a and 3b's windows are cut by this script — a rolling 5-hour slide
// and a natural 7-day bin from the earliest event, both arbitrary starting
// points chosen here. Block 3c's two windows are not: they are the
// account's own quota windows, anchored to the `resets_at` Claude Code
// itself reported, captured in this directory's
// `quota-capture-260920T163041Z.txt`. All three answer "how many tokens
// landed in some window", but the three windows start at three different
// times, and a figure read from one is not a figure from another.

const fs = require('node:fs');
const path = require('node:path');
const { execSync } = require('node:child_process');
const registry = require('../../../../lib/registry.js');
const prices = require('../../../../lib/prices.js');
const spend = require('../../../../lib/spend.js');

const ROOT = path.resolve(__dirname, '..', '..', '..', '..');

// The account's two quota windows, read once from this directory's
// `quota-capture-260920T163041Z.txt` (a single statusline payload capture,
// n = 1) rather than computed here — `resets_at` is not on disk anywhere
// this script already reads, and deriving it from anything else would be a
// third clock this file invented.
const QUOTA_WINDOWS = [
    { window: '5h', from: '2026-09-20T15:40:00.000Z', to: '2026-09-20T20:40:00.000Z' },
    { window: '7d', from: '2026-09-17T19:00:00.000Z', to: '2026-09-24T19:00:00.000Z' },
];

const short8 = (id) => String(id).slice(0, 8);

// A session's `spend` field, or null when it is missing or the wrong shape —
// the same gate `lib/spend.js`'s `rowFor` applies, repeated here so block 1,
// block 2 and block 3 all draw from one identical population.
function spendFieldOf(data) {
    return data && typeof data.spend === 'object' && data.spend && !Array.isArray(data.spend)
        ? data.spend : null;
}

// Raw token totals for one side of a stage (`w.spend.models` or
// `w.spend.subagents.models`), summed across whatever models are in it. This
// does not consult `prices.rateFor` the way the usd side does — an unpriced
// model still ran real tokens, and the token columns are not a price.
function tokensOf(models) {
    const t = { input: 0, output: 0, cacheRead: 0, cacheWrite: 0 };
    for (const tok of Object.values(models || {})) {
        t.input += tok.input || 0;
        t.output += tok.output || 0;
        t.cacheRead += tok.cacheRead || 0;
        t.cacheWrite += (tok.cacheWrite5m || 0) + (tok.cacheWrite1h || 0);
    }
    return t;
}

const tokenTotal = (t) => t.input + t.output + t.cacheRead + t.cacheWrite;

// 4 decimals, not 2: a single stage's slice of a session can be a fraction
// of a cent, and rounding to 2 would print several distinct stages as the
// same "$0.00".
const usdCell = (n) => (n == null ? '—' : n.toFixed(4));

// One header row and a matching list of cell-arrays becomes one
// tab-separated table — the one shape all four tables below share.
const tsv = (header, rows) => [header, ...rows].map((r) => r.join('\t')).join('\n');

// The request-count bucket `lib/spend.js`'s own `buckets()` would put this
// row in — asked for through that exported function rather than its
// un-exported `rangeFor`, by handing it a one-row array and reading off
// whichever of the four ranges comes back with `count: 1`.
function bucketFor(row) {
    const hit = spend.buckets([row]).find((b) => b.count === 1);
    return hit ? hit.range : '—';
}

// --- block 1: per-stage rows ------------------------------------------------

function stageRows(sessionId, data, requests, bucket) {
    const version = typeof data.version === 'string' ? data.version : '—';
    const rows = [];
    for (const w of registry.seriesOf(data)) {
        const ownModels = w.spend && w.spend.models ? w.spend.models : null;
        const agentModels = w.spend && w.spend.subagents && w.spend.subagents.models
            ? w.spend.subagents.models : null;
        // At least one row per stage even when neither side has spend on
        // record — the stage still happened and belongs on the printout —
        // and a second row only when the agents side is actually present.
        const sides = [];
        if (ownModels) sides.push(['parent', ownModels]);
        if (agentModels) sides.push(['agents', agentModels]);
        if (!sides.length) sides.push(['parent', null]);
        for (const [who, models] of sides) {
            const cost = models ? prices.costOf(models) : null;
            const usd = cost && cost.priced.length ? cost.usd : null;
            const tok = models ? tokensOf(models) : { input: 0, output: 0, cacheRead: 0, cacheWrite: 0 };
            rows.push({
                session: short8(sessionId), version, requests, bucket, stage: w.stage, from: w.from, to: w.to,
                who, usd, input: tok.input, output: tok.output, cacheRead: tok.cacheRead, cacheWrite: tok.cacheWrite,
            });
        }
    }
    return rows;
}

function stageTable(rows) {
    const header = ['session', 'version', 'requests', 'bucket', 'stage', 'from', 'to', 'who', 'usd', 'in', 'out', 'cacheR', 'cacheW'];
    const body = rows.map((r) => [
        r.session, r.version, r.requests, r.bucket, r.stage, r.from, r.to, r.who, usdCell(r.usd),
        r.input, r.output, r.cacheRead, r.cacheWrite,
    ]);
    return tsv(header, body);
}

// --- block 2: crosscheck -----------------------------------------------------

// One session's per-stage usd, summed the same way block 1 prints it — both
// sides, `costOf(...).usd` taken as-is (0 for an empty or fully unpriced
// side, which is what a bare sum needs; block 1's `null`-vs-`—` distinction
// is a display choice, not an arithmetic one).
function stageSumOf(data) {
    let total = 0;
    for (const w of registry.seriesOf(data)) {
        if (w.spend && w.spend.models) total += prices.costOf(w.spend.models).usd;
        if (w.spend && w.spend.subagents && w.spend.subagents.models) {
            total += prices.costOf(w.spend.subagents.models).usd;
        }
    }
    return total;
}

function crosscheck(sessionRows, spendEntries) {
    const wholeOf = new Map(sessionRows.map((r) => [r.sessionId, r.usd]));
    let compared = 0;
    const mismatches = [];
    for (const { sessionId, data } of spendEntries) {
        const stageSum = stageSumOf(data);
        const whole = wholeOf.has(sessionId) ? wholeOf.get(sessionId) : null;
        compared += 1;
        if (whole == null) {
            mismatches.push({ sessionId, stageSum, whole: null, diff: null });
            continue;
        }
        const equalToTheCent = Math.round(stageSum * 100) === Math.round(whole * 100);
        if (!equalToTheCent) {
            mismatches.push({ sessionId, stageSum, whole, diff: stageSum - whole });
        }
    }
    return { compared, mismatches };
}

function crosscheckTable(mismatches) {
    const header = ['session', 'stage-sum-usd', 'whole-usd', 'diff'];
    const body = mismatches.map((m) => [
        short8(m.sessionId),
        m.stageSum.toFixed(4),
        m.whole == null ? 'missing' : m.whole.toFixed(4),
        m.diff == null ? 'n/a' : m.diff.toFixed(4),
    ]);
    return tsv(header, body);
}

// --- block 3: windows ---------------------------------------------------------

// One event per stage of one session with a `spend` field: its end time and
// its total token footprint (parent plus agents, all four components
// added). This is the flat timeline block 3 slides its windows across.
function stageEvents(spendEntries) {
    const events = [];
    for (const { sessionId, data } of spendEntries) {
        for (const w of registry.seriesOf(data)) {
            const own = tokensOf(w.spend && w.spend.models ? w.spend.models : null);
            const agents = tokensOf(w.spend && w.spend.subagents && w.spend.subagents.models ? w.spend.subagents.models : null);
            events.push({ sessionId, stage: w.stage, to: w.to, tokens: tokenTotal(own) + tokenTotal(agents) });
        }
    }
    return events;
}

// Every candidate window starts exactly at some event's `to`: sliding a
// window's left edge to any other point either drops an event (lower sum)
// or gains none (same sum, later start), so the maximum over any window of
// this length is always achieved by one of these starts. O(n^2) is fine at
// this event count (a few hundred stages across ~80 priced sessions).
function rollingWindows(events, hours) {
    const spanMs = hours * 3600 * 1000;
    const sorted = [...events].sort((a, b) => a.to - b.to);
    return sorted.map((e) => {
        const start = e.to;
        const end = start + spanMs;
        let tokens = 0;
        let stages = 0;
        const sessions = new Set();
        for (const other of sorted) {
            if (other.to >= start && other.to < end) {
                tokens += other.tokens;
                stages += 1;
                sessions.add(other.sessionId);
            }
        }
        return { start, tokens, sessions: sessions.size, stages };
    });
}

function windowTable(list) {
    const header = ['window start(ISO)', 'tokens', 'sessions', 'stages'];
    const body = list.map((w) => [new Date(w.start).toISOString(), w.tokens, w.sessions, w.stages]);
    return tsv(header, body);
}

// Natural, non-overlapping 7-day bins starting at the earliest event on the
// timeline — bin 0 is [earliest, earliest+7d), bin 1 the next 7 days, and so
// on, every bin printed whether or not it has events.
function sevenDayBins(events) {
    if (!events.length) return [];
    const minTo = Math.min(...events.map((e) => e.to));
    const spanMs = 7 * 24 * 3600 * 1000;
    const bins = new Map();
    for (const e of events) {
        const idx = Math.floor((e.to - minTo) / spanMs);
        if (!bins.has(idx)) bins.set(idx, { tokens: 0, sessions: new Set(), stages: 0 });
        const b = bins.get(idx);
        b.tokens += e.tokens;
        b.sessions.add(e.sessionId);
        b.stages += 1;
    }
    const maxIdx = Math.max(...bins.keys());
    const out = [];
    for (let idx = 0; idx <= maxIdx; idx++) {
        const b = bins.get(idx) || { tokens: 0, sessions: new Set(), stages: 0 };
        out.push({
            idx, start: minTo + idx * spanMs, end: minTo + (idx + 1) * spanMs,
            tokens: b.tokens, sessions: b.sessions.size, stages: b.stages,
        });
    }
    return out;
}

function binsTable(list) {
    const header = ['window start(ISO)', 'window end(ISO)', 'tokens', 'sessions', 'stages'];
    const body = list.map((b) => [
        new Date(b.start).toISOString(), new Date(b.end).toISOString(), b.tokens, b.sessions, b.stages,
    ]);
    return tsv(header, body);
}

// --- block 3c: quota windows -------------------------------------------------

// Block 1's own rows (full population, all buckets — a quota window does not
// care which bucket a session's request count fell in, for the same reason
// block 3a and 3b do not) filtered to the two windows in `QUOTA_WINDOWS`, by
// the same `to`-timestamp placement block 3a and 3b use.
function quotaWindowRows(allRows) {
    return QUOTA_WINDOWS.map((win) => {
        const from = Date.parse(win.from);
        const to = Date.parse(win.to);
        const hit = allRows.filter((r) => r.to >= from && r.to < to);
        const sessions = new Set(hit.map((r) => r.session)).size;
        const usd = hit.reduce((n, r) => n + (r.usd == null ? 0 : r.usd), 0);
        const input = hit.reduce((n, r) => n + r.input, 0);
        const output = hit.reduce((n, r) => n + r.output, 0);
        const cacheRead = hit.reduce((n, r) => n + r.cacheRead, 0);
        const cacheWrite = hit.reduce((n, r) => n + r.cacheWrite, 0);
        const totalTokens = input + output + cacheRead + cacheWrite;
        const nonCache = input + output;
        const cacheReadPct = totalTokens > 0 ? (cacheRead / totalTokens) * 100 : 0;
        return {
            window: win.window, from: win.from, to: win.to,
            sessions, stageRows: hit.length, usd,
            input, output, cacheRead, cacheWrite, totalTokens, cacheReadPct, nonCache,
        };
    });
}

function quotaTable(list) {
    const header = ['window', 'from(ISO)', 'to(ISO)', 'sessions', 'stage_rows', 'usd', 'in', 'out', 'cacheR', 'cacheW', 'total_tokens', 'cacheR_pct', 'non_cache'];
    const body = list.map((q) => [
        q.window, q.from, q.to, q.sessions, q.stageRows, usdCell(q.usd),
        q.input, q.output, q.cacheRead, q.cacheWrite, q.totalTokens,
        q.cacheReadPct.toFixed(1) + '%', q.nonCache,
    ]);
    return tsv(header, body);
}

// --- main -----------------------------------------------------------------

function main() {
    const { entries, unreadable } = registry.readAll(ROOT);
    const spendEntries = entries
        .map((e) => ({ sessionId: e.sessionId, data: e.data }))
        .filter((e) => spendFieldOf(e.data));

    const { rows: sessionRows } = spend.sessionsOf([ROOT]);
    const rowBySession = new Map(sessionRows.map((r) => [r.sessionId, r]));

    let allRows = [];
    for (const { sessionId, data } of spendEntries) {
        const row = rowBySession.get(sessionId) || null;
        const requests = row ? row.requests : '—';
        const bucket = row ? bucketFor(row) : '—';
        allRows = allRows.concat(stageRows(sessionId, data, requests, bucket));
    }

    const { compared, mismatches } = crosscheck(sessionRows, spendEntries);

    const events = stageEvents(spendEntries);
    const rolling = rollingWindows(events, 5);
    const top10 = [...rolling].sort((a, b) => b.tokens - a.tokens).slice(0, 10);
    const bins = sevenDayBins(events);

    const parts = [];
    parts.push('# .fankeel/sessions scanned: ' + entries.length + ' entries, ' + unreadable
        + ' unreadable (parse failures skipped and counted), ' + spendEntries.length + ' carry a spend field');
    parts.push('');
    parts.push('## block 1: per-stage (every spend-bearing session, all buckets — filter on `bucket` for the long-task end)');
    parts.push(stageTable(allRows));
    parts.push('');
    parts.push('## block 2: crosscheck (per-stage usd summed vs. lib/spend.js sessionsOf whole-session usd)');
    if (mismatches.length) {
        parts.push(crosscheckTable(mismatches));
    }
    parts.push('crosscheck: ' + compared + ' sessions compared, ' + mismatches.length + ' mismatched');
    parts.push('');
    parts.push('## block 3a: rolling 5-hour windows, top 10 by total tokens (full population, not bucket-filtered — a usage cap does not care which bucket a session is in)');
    parts.push(windowTable(top10));
    parts.push('');
    parts.push('## block 3b: natural 7-day windows, from the earliest event (full population, not bucket-filtered)');
    parts.push(binsTable(bins));
    parts.push('');
    parts.push('## block 3c: account quota windows (full population, not bucket-filtered — anchored to the resets_at in quota-capture-260920T163041Z.txt)');
    parts.push(quotaTable(quotaWindowRows(allRows)));

    const text = parts.join('\n') + '\n';

    let sha = 'unknown';
    try {
        sha = execSync('git rev-parse --short HEAD', { cwd: ROOT }).toString().trim();
    } catch (e) {
        // Left as 'unknown' — this script still prints to stdout even without git.
    }
    const outPath = path.join(__dirname, 'stages-at-' + sha + '.txt');
    fs.writeFileSync(outPath, text);
    process.stdout.write(text);
    return { outPath, compared, mismatches, top10, bins };
}

main();
